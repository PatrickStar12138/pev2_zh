export function t(key: keyof typeof messages | string, params?: MessageParams) {
  let value: string = (messages[key as keyof typeof messages] as string | undefined) || key
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(replacement ?? ""))
    }
  }
  return value
}

export function tp(label: string | undefined) {
  if (!label) return ""
  return nodePropLabels[label] || label
}

export function tt(term: string | undefined) {
  if (!term) return ""
  const sorted = Object.keys(planTermLabels).sort((a, b) => b.length - a.length)
  let result = term
  for (const key of sorted) {
    result = result.split(key).join(planTermLabels[key])
  }
  return result
}

export function tn(nodeType: string | undefined) {
  return tt(nodeType)
}

export function boolLabel(value: boolean) {
  return value ? t("app.yes") : t("app.no")
}
